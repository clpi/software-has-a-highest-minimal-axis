#!/usr/bin/env python3
"""Encode a solver instance as Lean data for the expectations gate.

Reads one or more instance files in the solver's JSON schema that
share axes, components, contract, and hyperedges (the arena seeds
share everything but the behavior table) and writes a Lean file
holding the instance in the encoding the proved core uses:

  - axis values are coded by their position in the axis value list;
  - configurations are functions from axis indices to codes, built
    from the coded contract rows;
  - behavior values are coded per component by first occurrence, and
    the flat behavior table is keyed by the mixed radix key of the
    configuration, so the behavior function is a table lookup.

Liveness, the emergence measure, and everything the gate compares
depend only on which values are equal, never on the values
themselves, and the coding preserves equality exactly: two values
share a code if and only if they are the same JSON value. The
expectations program then evaluates the proved definitions on the
coded instance.

Usage: python3 encode.py <out.lean> <instance.json> [<instance.json> ...]

Python 3, standard library only.
"""

import json
import sys


def code_instance(inst):
    axes = inst["axes"]
    axis_names = [axis["name"] for axis in axes]
    ranges = [len(axis["values"]) for axis in axes]
    coded_rows = []
    for row in inst["contract"]:
        coded = []
        for axis, value in zip(axes, row):
            coded.append(axis["values"].index(value))
        coded_rows.append(coded)
    comps = list(inst["components"])
    tables = {}
    for comp in comps:
        seen = []
        for value in inst["behavior"][comp]:
            if value not in seen:
                seen.append(value)
        tables[comp] = [seen.index(value) for value in inst["behavior"][comp]]
    edges = []
    for edge in inst.get("hyperedges", []):
        members = [comps.index(name) for name in edge["components"]]
        edges.append((sorted(members), edge.get("weight", 1)))
    return axis_names, ranges, coded_rows, comps, tables, edges


def key_of(coded_row, ranges):
    key = coded_row[0]
    for k in range(1, len(coded_row)):
        key = key * ranges[k] + coded_row[k]
    return key


def flat_table(coded_rows, ranges, comps, tables):
    size = 1
    for r in ranges:
        size *= r
    flat = [0] * (size * len(comps))
    for i, row in enumerate(coded_rows):
        key = key_of(row, ranges)
        for j, comp in enumerate(comps):
            flat[key * len(comps) + j] = tables[comp][i]
    return flat


def num_list(values):
    return "[" + ", ".join(str(v) for v in values) + "]"


def main(argv):
    if len(argv) < 3:
        sys.stderr.write(
            "usage: python3 encode.py <out.lean> <instance.json> "
            "[<instance.json> ...]\n")
        return 2
    out_path = argv[1]
    insts = []
    for path in argv[2:]:
        with open(path, "r", encoding="utf-8") as handle:
            insts.append(json.load(handle))
    coded = [code_instance(inst) for inst in insts]
    axis_names, ranges, coded_rows, comps, _, edges = coded[0]
    for other in coded[1:]:
        if other[0] != axis_names or other[1] != ranges \
                or other[2] != coded_rows or other[3] != comps \
                or other[5] != edges:
            sys.stderr.write(
                "instances disagree on axes, contract, components, "
                "or hyperedges\n")
            return 1
    for members, weight in edges:
        if weight != 1:
            sys.stderr.write(
                "this encoder lands weight one hyperedges only\n")
            return 1
    n_axes = len(axis_names)
    n_comps = len(comps)
    lines = []
    lines.append("/-")
    lines.append("  The arena instances, in the encoding of the proved core.")
    lines.append("")
    lines.append("  This file is generated by solver/encode.py from the")
    lines.append("  arena instance files in solver/instances/; regenerate")
    lines.append("  it from the proof directory with")
    lines.append("")
    cmd = " ".join(
        "../solver/instances/%s" % path.split("/")[-1] for path in argv[2:])
    lines.append("    python3 ../solver/encode.py Arena.lean %s" % cmd)
    lines.append("")
    lines.append("  and do not edit it by hand. The encoding: axis values")
    lines.append("  are coded by their position in the axis value list; a")
    lines.append("  configuration is a function from axis indices to codes,")
    lines.append("  read out of the flat array of coded contract values;")
    lines.append("  behavior values are")
    lines.append("  coded per component by first occurrence, and the flat")
    lines.append("  behavior table is keyed by the mixed radix key of the")
    lines.append("  configuration. Liveness and the emergence measure")
    lines.append("  depend only on which values are equal, and the coding")
    lines.append("  preserves equality exactly, so the proved definitions")
    lines.append("  evaluated on the coded instance give the instance's")
    lines.append("  own values.")
    lines.append("-/")
    lines.append("")
    lines.append("import Hma")
    lines.append("")
    lines.append("open Hma")
    lines.append("")
    lines.append("namespace Arena")
    lines.append("")
    lines.append("/-- The coded contract values, row after row in")
    lines.append("    instance order. -/")
    flat_vals = [v for row in coded_rows for v in row]
    lines.append("def vals : Array Nat := #[")
    chunk = 28
    vparts = []
    for start in range(0, len(flat_vals), chunk):
        vparts.append(", ".join(str(v) for v in flat_vals[start:start + chunk]))
    for j, part in enumerate(vparts):
        comma = "," if j < len(vparts) - 1 else "]"
        lead = "  " if j == 0 else "   "
        lines.append("%s%s%s" % (lead, part, comma))
    lines.append("")
    lines.append("/-- A configuration from the row of its values. -/")
    lines.append(
        "def rowfun (i : Nat) (a : Fin %d) : Nat := "
        "(vals[i * %d + a.1]?).getD 0" % (n_axes, n_axes))
    lines.append("")
    lines.append("/-- The mixed radix key of a configuration. -/")
    expr = "(x 0)"
    for k in range(1, n_axes):
        expr = "(%s * %d + (x %d))" % (expr, ranges[k], k)
    lines.append("def keyof (x : Fin %d → Nat) : Nat := %s" % (n_axes, expr))
    lines.append("")
    for idx, (inst, entry) in enumerate(zip(insts, coded)):
        tables = entry[4]
        flat = flat_table(coded_rows, ranges, comps, tables)
        lines.append(
            "/-- The coded behavior table of instance %s. -/"
            % inst.get("name", ""))
        lines.append("def table%d : Array Nat := #[" % idx)
        chunk = 20
        parts = []
        for start in range(0, len(flat), chunk):
            parts.append(", ".join(str(v) for v in flat[start:start + chunk]))
        for j, part in enumerate(parts):
            comma = "," if j < len(parts) - 1 else "]"
            lead = "  " if j == 0 else "   "
            lines.append("%s%s%s" % (lead, part, comma))
        lines.append("")
        lines.append(
            "/-- Instance %s in the encoding of the proved core. -/"
            % inst.get("name", ""))
        lines.append(
            "def inst%d : Inst (Fin %d) Nat (Fin %d) Nat where"
            % (idx, n_axes, n_comps))
        lines.append("  axes := %s" % num_list(list(range(n_axes))))
        lines.append("  axesnodup := by decide")
        lines.append("  axescomplete := by decide")
        lines.append("  comps := %s" % num_list(list(range(n_comps))))
        lines.append(
            "  contract := (List.range %d).map rowfun" % len(coded_rows))
        lines.append(
            "  beh := fun x b => (table%d[(keyof x * %d + b.1)]?).getD 0"
            % (idx, n_comps))
        edge_strs = [num_list(members) for members, _ in edges]
        lines.append("  edges := [%s]" % ", ".join(edge_strs))
        lines.append("  weight := fun _ => 1")
        lines.append("  weightpos := by")
        lines.append("    intro e _ _")
        lines.append("    decide")
        lines.append("")
    lines.append("end Arena")
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
